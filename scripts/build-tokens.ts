// Turns design/variables_tokens.json (read-only design export) into styles/tokens.css.
// Run: npm run tokens:build. Node's built-in type stripping runs this file, so keep to
// erasable TypeScript (no enums, no parameter properties) and `.ts` import extensions.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// WHY: matches Tailwind's `md` breakpoint (48rem). One breakpoint in the product (plan §8).
const DESKTOP_MIN_WIDTH = "48rem";

type Alias = { type: "VARIABLE_ALIAS"; collection: string; name: string };
type Variable = { name: string; token: string; type: string; value: string | number; values: Record<string, string | number | Alias> };
type Collection = { variables: { colors: Variable[]; numbers: Variable[]; strings: Variable[] } };
type TextStyle = { name: string; fontFamily: string; fontWeight: string; fontSize: string; lineHeight: number; letterSpacing: string };
type Effect = { type: string; color: string; offset: { x: number; y: number }; radius: number; spread: number; visible: boolean };
type EffectStyle = { name: string; effects: Effect[] };
export type TokenExport = {
  styles: { textStyles: TextStyle[]; effectStyles: EffectStyle[] };
  collections: { Primitives: Collection; Tokens: Collection; Typography: Collection };
};

const HEADER = `/* GENERATED by scripts/build-tokens.ts from design/variables_tokens.json.
   Do not edit. Run \`npm run tokens:build\`. \`npm run tokens:check\` fails if this file is stale. */
`;

function fail(message: string): never {
  throw new Error(`build-tokens: ${message}`);
}

function isAlias(v: unknown): v is Alias {
  return typeof v === "object" && v !== null && (v as Alias).type === "VARIABLE_ALIAS";
}

function modeValue(v: Variable): string | number | Alias {
  const first = Object.values(v.values)[0];
  if (first === undefined) fail(`${v.name} has no value`);
  return first;
}

export function fmt(n: number): string {
  return String(Number(n.toFixed(6)));
}
export function rem(px: number): string {
  return px === 0 ? "0" : `${fmt(px / 16)}rem`;
}
function px(n: number): string {
  return n === 0 ? "0" : `${fmt(n)}px`;
}

// WHY: the export names `sizing/:5` as token `sizing-5`, colliding with `sizing/5`. We key on
// `name` and rename `:25`, `:5`, `1:5` to `0-25`, `0-5`, `1-5` (plan §8, open item 2).
export function sizingKey(name: string): string {
  const key = name.replace(/^sizing\//, "");
  const m = /^(\d*):(\d+)$/.exec(key);
  return m ? `${m[1] || "0"}-${m[2]}` : key;
}

function kebab(s: string): string {
  return s.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function decl(name: string, value: string): string {
  return `  ${name}: ${value};`;
}

function noDuplicates(names: string[], what: string): void {
  const seen = new Set<string>();
  for (const n of names) {
    if (seen.has(n)) fail(`duplicate ${what} output "${n}"`);
    seen.add(n);
  }
}

export function buildTokensCss(data: TokenExport): string {
  const { Primitives, Tokens, Typography } = data.collections;

  // --- Primitives: colours -------------------------------------------------------------
  const colourValues = new Map<string, string>();
  const rootColours: string[] = [];
  for (const v of Primitives.variables.colors) {
    const val = modeValue(v);
    if (typeof val !== "string") fail(`primitive colour ${v.name} must be a literal`);
    const cssName = `--${v.name.replace(/\//g, "-")}`;
    if (colourValues.has(cssName)) fail(`duplicate colour output "${cssName}"`);
    colourValues.set(cssName, val);
    rootColours.push(decl(cssName, val));
  }

  // --- Primitives: sizing (rem) --------------------------------------------------------
  const sizing = new Map<string, number>();
  const rootSizing: string[] = [];
  for (const v of Primitives.variables.numbers) {
    if (!v.name.startsWith("sizing/")) fail(`unknown primitive number group "${v.name}"`);
    const val = modeValue(v);
    if (typeof val !== "number") fail(`${v.name} must be a number`);
    const key = sizingKey(v.name);
    if (sizing.has(key)) fail(`duplicate sizing output "--sizing-${key}"`);
    sizing.set(key, val);
    rootSizing.push(decl(`--sizing-${key}`, rem(val)));
  }

  // Resolve a Tokens number to px, following the alias to its primitive.
  function numberPx(v: Variable): { px: number; sizingKey?: string } {
    const val = modeValue(v);
    if (typeof val === "number") return { px: val };
    if (isAlias(val)) {
      const key = sizingKey(val.name);
      const target = sizing.get(key);
      if (!val.name.startsWith("sizing/") || target === undefined) fail(`${v.name} aliases missing primitive "${val.name}"`);
      return { px: target, sizingKey: key };
    }
    return fail(`${v.name} has unsupported value`);
  }

  // --- Tokens: numbers, by group -------------------------------------------------------
  const spacingTheme: string[] = [];
  const spacingKeys: string[] = [];
  const radiusTheme: string[] = [];
  const rootMisc: string[] = [];
  const borderUtilities: string[] = [];
  let focusWidth = "";
  let focusOffset = "";

  for (const v of Tokens.variables.numbers) {
    const [group = "", ...rest] = v.name.split("/");
    const key = rest.join("/");
    const { px: value, sizingKey: sk } = numberPx(v);
    if (group === "spacing") {
      // WHY: the key is the pixel value (`p-16` = 16px), not Tailwind's default 4px scale.
      spacingKeys.push(key);
      spacingTheme.push(decl(`--spacing-${key}`, sk ? `var(--sizing-${sk})` : rem(value)));
    } else if (group === "border-width") {
      rootMisc.push(decl(`--border-width-${key}`, px(value)));
      // Tailwind v4 already emits integer `border-N`; fractions need their own utility.
      if (!Number.isInteger(value)) {
        borderUtilities.push(
          `@utility border-${key} {\n  border-style: solid;\n  border-width: var(--border-width-${key});\n}`,
        );
      }
    } else if (group === "border-radius") {
      const name = key.replace(/^rounded-?/, "") || "DEFAULT";
      radiusTheme.push(decl(name === "DEFAULT" ? "--radius" : `--radius-${name}`, name === "full" ? px(value) : rem(value)));
    } else if (group === "icon-size" || group === "size") {
      spacingKeys.push(`${group === "icon-size" ? "icon-" : ""}${key}`);
      spacingTheme.push(decl(`--spacing-${group === "icon-size" ? "icon-" : ""}${key}`, rem(value)));
    } else if (group === "focus") {
      if (key === "ring-width") focusWidth = px(value);
      else if (key === "ring-offset") focusOffset = px(value);
      else fail(`unknown focus token "${v.name}"`);
    } else {
      fail(`unknown token number group "${v.name}"; decide how it maps before adding it`);
    }
  }
  if (!focusWidth || !focusOffset) fail("focus/ring-width and focus/ring-offset are required");
  noDuplicates(spacingTheme, "spacing");

  // --- Tokens: colours (aliases) -------------------------------------------------------
  const colourTheme: string[] = [];
  const tokenColourTargets = new Map<string, string>();
  for (const v of Tokens.variables.colors) {
    const val = modeValue(v);
    const themeName = `--color-${v.name.replace(/^colour\//, "").replace(/\//g, "-")}`;
    if (isAlias(val)) {
      const target = `--${val.name.replace(/\//g, "-")}`;
      if (!colourValues.has(target)) fail(`${v.name} aliases missing primitive "${val.name}"`);
      colourTheme.push(decl(themeName, `var(${target})`));
      tokenColourTargets.set(v.name, target);
    } else if (typeof val === "string") {
      colourTheme.push(decl(themeName, val));
    } else {
      fail(`${v.name} has unsupported value`);
    }
  }
  noDuplicates(colourTheme.map((l) => l.split(":")[0] ?? ""), "colour");
  const focusTarget = tokenColourTargets.get("colour/border/focus");
  const focusInverseTarget = tokenColourTargets.get("colour/border/inverse");
  if (!focusTarget || !focusInverseTarget) fail("colour/border/focus and colour/border/inverse must be aliases");

  // --- Typography ----------------------------------------------------------------------
  const typeNumbers = Typography.variables.numbers.map((v) => {
    const val = modeValue(v);
    if (typeof val !== "number") fail(`${v.name} must be a number`);
    return decl(`--${v.token}`, v.name.startsWith("fontSize/") ? rem(val) : String(val));
  });
  const strings = new Map(Typography.variables.strings.map((v) => [v.name, String(modeValue(v))]));
  const bodyFamily = strings.get("font/body");
  const headingFamily = strings.get("font/heading");
  if (!bodyFamily || !headingFamily) fail("font/body and font/heading are required");
  // WHY: next/font exposes each family as `--font-<kebab family>`; app/fonts.ts uses the same names.
  const stackBody = `var(--font-${kebab(bodyFamily)}), system-ui, sans-serif`;
  const stackHeading = `var(--font-${kebab(headingFamily)}), serif`;

  function textBody(s: TextStyle, indent: string): string {
    const size = Number.parseFloat(s.fontSize);
    if (!Number.isFinite(size) || !s.fontSize.endsWith("px")) fail(`${s.name}: font size must be px`);
    const spacing = s.letterSpacing === "0%" ? "0" : fail(`${s.name}: unsupported letter spacing ${s.letterSpacing}`);
    return [
      `font-family: var(--font-stack-${s.fontFamily === headingFamily ? "heading" : "body"});`,
      `font-size: ${rem(size)};`,
      `line-height: ${fmt(Math.round(s.lineHeight * 100) / 100)};`,
      `font-weight: ${s.fontWeight};`,
      `letter-spacing: ${spacing};`,
    ]
      .map((l) => `${indent}${l}`)
      .join("\n");
  }

  const textUtilities: string[] = [];
  const headings = new Map<string, { mobile?: TextStyle; desktop?: TextStyle }>();
  for (const s of data.styles.textStyles) {
    const parts = s.name.split("/");
    if (parts[0] === "body") {
      const [, size = "", weight = ""] = parts;
      textUtilities.push(`@utility text-body-${size.replace(/^text-/, "")}-${weight} {\n${textBody(s, "  ")}\n}`);
    } else if (parts[0] === "heading") {
      const level = (parts[2] ?? "").replace(/^heading /, "");
      const entry = headings.get(level) ?? {};
      if (parts[1] === "mobile") entry.mobile = s;
      else if (parts[1] === "desktop") entry.desktop = s;
      else fail(`unknown heading mode in ${s.name}`);
      headings.set(level, entry);
    } else {
      fail(`unknown text style group "${s.name}"`);
    }
  }
  for (const [level, { mobile, desktop }] of headings) {
    if (!mobile || !desktop) fail(`heading ${level} needs mobile and desktop styles`);
    textUtilities.push(
      `@utility text-heading-${level} {\n${textBody(mobile, "  ")}\n  @media (width >= ${DESKTOP_MIN_WIDTH}) {\n${textBody(desktop, "    ")}\n  }\n}`,
    );
  }
  noDuplicates(textUtilities.map((u) => u.split(" ")[1] ?? ""), "text utility");

  // --- Effects -------------------------------------------------------------------------
  const shadowTheme: string[] = [];
  for (const e of data.styles.effectStyles) {
    const [group, name] = e.name.split("/");
    const fx = e.effects[0];
    if (group !== "elevation" || !name || e.effects.length !== 1 || !fx || fx.type !== "DROP_SHADOW") {
      fail(`unsupported effect style "${e.name}"`);
    }
    shadowTheme.push(decl(`--shadow-${name}`, `${px(fx.offset.x)} ${px(fx.offset.y)} ${px(fx.radius)} ${px(fx.spread)} ${fx.color}`));
  }

  // --- Output --------------------------------------------------------------------------
  return `${HEADER}
:root {
${[...rootColours, ...rootSizing, ...rootMisc, ...typeNumbers].join("\n")}
${decl("--font-stack-body", stackBody)}
${decl("--font-stack-heading", stackHeading)}
${decl("--focus-ring-width", focusWidth)}
${decl("--focus-ring-offset", focusOffset)}
}

/* Reset Tailwind's defaults so only approved tokens produce utilities (p-5, text-sm and rounded-[3px] emit nothing).
   Breakpoints, animations and easing keep Tailwind's defaults; \`md\` is 48rem. */
@theme {
  --color-*: initial;
  --spacing-*: initial;
  --spacing: initial;
  --radius-*: initial;
  --text-*: initial;
  --font-*: initial;
  --font-weight-*: initial;
  --leading-*: initial;
  --tracking-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --container-*: initial;
  --blur-*: initial;
  --text-shadow-*: initial;
  --perspective-*: initial;
}

@theme inline {
${[...colourTheme, ...spacingTheme, ...radiusTheme, ...shadowTheme].join("\n")}
${decl("--font-body", "var(--font-stack-body)")}
${decl("--font-heading", "var(--font-stack-heading)")}
}

${borderUtilities.join("\n\n")}

/* Keyboard focus ring: border/focus on light surfaces, border/inverse on ink surfaces (plan §8). */
@utility focus-ring {
  &:focus-visible {
    outline: var(--focus-ring-width) solid var(${focusTarget});
    outline-offset: var(--focus-ring-offset);
  }
}

@utility focus-ring-inverse {
  &:focus-visible {
    outline: var(--focus-ring-width) solid var(${focusInverseTarget});
    outline-offset: var(--focus-ring-offset);
  }
}

${textUtilities.join("\n\n")}
`;
}

export function readTokenExport(root: string): TokenExport {
  return JSON.parse(readFileSync(resolve(root, "design/variables_tokens.json"), "utf8")) as TokenExport;
}

export function normalizeEol(s: string): string {
  return s.replace(/\r\n/g, "\n");
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(resolve(root, "styles/tokens.css"), buildTokensCss(readTokenExport(root)));
  console.log("styles/tokens.css written");
}
